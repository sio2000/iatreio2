-- Διόρθωση ειδικοτήτων ιατρών (Μάιος 2026)
-- Αντίγραψε και επικόλλησε αυτές τις εντολές στο SQL Editor του Supabase.
--
-- Αλλαγές:
-- 1) Η Μαρία Κ. Δημητριάδου μετακινείται στην κατηγορία
--    «Κλινική Παιδοψυχολόγος & Ψυχοθεραπεύτρια».
-- 2) Η ειδικότητα «Παιδοψυχολόγος & Ψυχοθεραπεύτρια» μετονομάζεται σε «Ψυχολόγος»,
--    οπότε όποιος γιατρός ανήκε σε αυτή (π.χ. Ειρήνη Στεργίου) γίνεται «Ψυχολόγος».
--
-- ΣΗΜΑΝΤΙΚΟ: Πρώτα μετακινούμε τη Μαρία στην «Κλινική Παιδοψυχολόγος & Ψυχοθεραπεύτρια»
-- και μετά κάνουμε bulk update των υπόλοιπων «Παιδοψυχολόγος & Ψυχοθεραπεύτρια» σε «Ψυχολόγος»,
-- ώστε να μην επηρεαστεί λάθος.

-- 1. Διόρθωση ειδικότητας Μαρίας Κ. Δημητριάδου
UPDATE public.doctors
SET specialty = 'Κλινική Παιδοψυχολόγος & Ψυχοθεραπεύτρια'
WHERE name = 'Μαρία Κ. Δημητριάδου';

-- 2. Μετονομασία ειδικότητας «Παιδοψυχολόγος & Ψυχοθεραπεύτρια» -> «Ψυχολόγος»
UPDATE public.doctors
SET specialty = 'Ψυχολόγος'
WHERE specialty = 'Παιδοψυχολόγος & Ψυχοθεραπεύτρια';

-- 3. (Προαιρετικό) Ενημέρωση ιστορικών ραντεβού ώστε το column appointments.specialty
--    να ταιριάζει με τις νέες ονομασίες (αν είχε αποθηκευτεί η παλιά τιμή ως κείμενο).
UPDATE public.appointments
SET specialty = 'Ψυχολόγος'
WHERE specialty = 'Παιδοψυχολόγος & Ψυχοθεραπεύτρια';

UPDATE public.appointments
SET specialty = 'Κλινική Παιδοψυχολόγος & Ψυχοθεραπεύτρια'
WHERE specialty IS NOT NULL
  AND specialty <> 'Κλινική Παιδοψυχολόγος & Ψυχοθεραπεύτρια'
  AND doctor_id = (SELECT id FROM public.doctors WHERE name = 'Μαρία Κ. Δημητριάδου');

-- 4. Έλεγχος ότι όλα είναι σωστά
SELECT id, name, specialty, active
FROM public.doctors
ORDER BY specialty, name;
